#!/usr/bin/env python3
"""Opt-in real Qwen LoRA stop/process-exit/resume demonstration on the prepared corpus.

Never invoked during repository generation. Four optimizer steps, same scheduler horizon
in both processes, actual Trainer checkpoints. No invented literary smoke dataset.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys
import uuid

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from tagore_llm.common import file_hash, load_config, read_json, write_json
from tagore_llm.checkpoints import checkpoint_inventory


def run_demo(root, sequence_length=None, generation=True):
    if not (root / "data/processed/dataset_manifest.json").exists():
        raise FileNotFoundError("Prepare and audit a verified dataset before running the recovery demonstration.")
    config = load_config(root, "training")
    config.update(run_name="recovery-demo-" + uuid.uuid4().hex[:10], max_steps=4,
                  gradient_accumulation_steps=1, save_steps=1, eval_steps=2,
                  save_total_limit=3, logging_steps=1, force_fresh=False,
                  early_stopping_patience=0)
    if sequence_length is not None:
        config["sequence_length"] = sequence_length
    path = root / "logs" / f"{config['run_name']}.json"
    write_json(path, config)
    command = [sys.executable, "-m", "tagore_llm.cli", "--root", str(root), "train", "--training-config", str(path)]
    # Phase 1 exits normally after step 2. Phase 2 is a NEW Python process with no in-memory training state.
    subprocess.run(command + ["--stop-after", "2", "--no-export"], cwd=root, check=True)
    run_dir = Path(config["checkpoint_root"])
    if not run_dir.is_absolute():
        run_dir = root / run_dir
    run_dir /= config["run_name"]
    state2 = read_json(run_dir / "checkpoint-2/trainer_state.json")
    assert state2["global_step"] == 2
    before = file_hash(run_dir / "checkpoint-2/adapter_model.safetensors")
    subprocess.run(command, cwd=root, check=True)
    state4 = read_json(run_dir / "checkpoint-4/trainer_state.json")
    assert state4["global_step"] == 4
    assert state4["epoch"] > state2["epoch"]
    assert file_hash(run_dir / "checkpoint-4/adapter_model.safetensors") != before
    import torch
    # Only load local trusted checkpoints generated by this project. Never accept arbitrary pickles.
    opt2 = torch.load(run_dir / "checkpoint-2/optimizer.pt", map_location="cpu", weights_only=False)
    opt4 = torch.load(run_dir / "checkpoint-4/optimizer.pt", map_location="cpu", weights_only=False)
    def optimizer_step(state):
        return max(int(x["step"]) for x in state["state"].values() if "step" in x)
    assert optimizer_step(opt2) == 2 and optimizer_step(opt4) == 4
    scheduler2 = torch.load(run_dir / "checkpoint-2/scheduler.pt", map_location="cpu", weights_only=False)
    scheduler4 = torch.load(run_dir / "checkpoint-4/scheduler.pt", map_location="cpu", weights_only=False)
    assert scheduler4["last_epoch"] > scheduler2["last_epoch"]
    inventory = checkpoint_inventory(run_dir, read_json(run_dir / "RUN.json"))
    assert inventory[0]["status"] == "complete" and inventory[0]["global_step"] == 4
    result = {"status": "passed", "run_dir": str(run_dir), "first_process_step": 2, "resumed_process_step": 4,
              "optimizer_steps": [optimizer_step(opt2), optimizer_step(opt4)],
              "scheduler_epochs": [scheduler2["last_epoch"], scheduler4["last_epoch"]],
              "checks": ["full-state save", "new-process resume", "adapter changed", "optimizer advanced", "scheduler advanced", "sealed checkpoints verified"]}
    if generation:
        from tagore_llm.evaluation import ComparisonSession, GenerationSettings, PROMPTS
        session = ComparisonSession(root, load_config(root))
        try:
            record = session.compare(PROMPTS["Nature imagery"], GenerationSettings(max_new_tokens=8))
            assert isinstance(record["base"]["text"], str) and isinstance(record["fine_tuned"]["text"], str)
            result["generation_comparison_id"] = record["comparison_id"]
            result["checks"].append("exported adapter load and saved Bengali-prompt generation comparison")
        finally:
            session.close()
    write_json(root / "evaluations" / f"{config['run_name']}.json", result)
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--execute", action="store_true", help="Actually load weights and train four optimizer steps")
    parser.add_argument("--skip-generation", action="store_true")
    args = parser.parse_args()
    if not args.execute:
        parser.exit(message="No training performed. Pass --execute after installing dependencies and preparing a corpus.\n")
    print(run_demo(ROOT, generation=not args.skip_generation))
